#!/usr/bin/env node
/**
 * Regenerates dev.cliproxyapi.opendeck.sdPlugin/lib/logos.mjs from the official provider marks
 * in the LobeHub icon set (@lobehub/icons-static-svg, MIT).
 *
 *   mkdir /tmp/lobe && cd /tmp/lobe && npm pack @lobehub/icons-static-svg && tar xzf *.tgz
 *   node scripts/vendor-logos.mjs /tmp/lobe/package
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgDir = process.argv[2];
if (!pkgDir) {
  console.error('usage: node scripts/vendor-logos.mjs <path-to-extracted-@lobehub/icons-static-svg/package>');
  process.exit(1);
}
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));

// provider key -> [colour file (used on keys), mono file (used for the mono theme)]
const SOURCES = {
  antigravity: ['antigravity-color', 'antigravity'],
  claude: ['claude-color', 'claude'],
  codex: ['codex-color', 'codex'],
  openai: ['openai', 'openai'],
  gemini: ['gemini-color', 'gemini'],
  geminicli: ['geminicli-color', 'geminicli'],
  kimi: ['kimi-color', 'kimi'],
  xai: ['grok', 'grok'],
  qwen: ['qwen-color', 'qwen'],
  meta: ['meta-color', 'meta'],
  devin: ['devin-color', 'devin'],
  deepseek: ['deepseek-color', 'deepseek'],
  cursor: ['cursor', 'cursor'],
  copilot: ['githubcopilot', 'githubcopilot'],
};

function inner(file, key, variant) {
  const svg = fs.readFileSync(path.join(pkgDir, 'icons', `${file}.svg`), 'utf8');
  const root = svg.match(/^<svg([^>]*)>/)[1];
  let body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>.*?<\/title>/, '');
  // Make ids unique per provider/variant so several logos can share one key image.
  const prefix = `lg-${key}-${variant}-`;
  body = body.replace(/lobe-icons-[A-Za-z0-9_-]+/g, (id) => prefix + id.replace(/^lobe-icons-[a-z]+-/, '').replace(/[^A-Za-z0-9-]/g, ''));
  const evenodd = /fill-rule="evenodd"/.test(root);
  const mono = /fill="currentColor"/.test(root);
  return { body, evenodd, mono };
}

const entries = Object.entries(SOURCES).map(([key, [colorFile, monoFile]]) => {
  const color = inner(colorFile, key, 'c');
  const mono = inner(monoFile, key, 'm');
  return `  ${key}: {\n    color: ${JSON.stringify(color.body)},\n    colorIsMono: ${color.mono},\n    mono: ${JSON.stringify(mono.body)},\n    evenodd: ${mono.evenodd || color.evenodd},\n  },`;
});

const out = `/**
 * GENERATED by scripts/vendor-logos.mjs — do not edit by hand.
 * Official provider marks from @lobehub/icons-static-svg@${pkg.version} (MIT License,
 * https://github.com/lobehub/lobe-icons). Logos are trademarks of their respective owners
 * and are used here only to identify each provider.
 *
 * Each entry is SVG markup on a 0 0 24 24 grid. \`color\` is the brand-coloured mark
 * (\`colorIsMono\` = it uses currentColor and needs a fill); \`mono\` is the single-colour mark.
 */
export const LOGOS = {
${entries.join('\n')}
};
`;
const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.join(here, '..', 'dev.cliproxyapi.opendeck.sdPlugin', 'lib', 'logos.mjs');
fs.writeFileSync(dest, out);
console.log(`Wrote ${Object.keys(SOURCES).length} logos to ${dest}`);
